// Known English messages from the auth server, mapped to catalog keys (matched case-insensitively)
const AUTH_ERRORS: [RegExp, keyof typeof authMessages.en][] = [
  [/invalid email or password|invalid password|invalid credentials/i, 'errInvalidCredentials'],
  [/already exists|already in use|already registered/i, 'errUserExists'],
  [/invalid email/i, 'errInvalidEmail'],
  [/password (is )?too short/i, 'errPasswordShort'],
  [/password (is )?too long/i, 'errPasswordLong'],
];

export function authErrorKey(message: string | undefined | null): keyof typeof authMessages.en | null {
  if (!message) return null;
  return AUTH_ERRORS.find(([re]) => re.test(message))?.[1] ?? null;
}
