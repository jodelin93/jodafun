// Known English validation messages from the server, mapped to catalog keys
export function renameErrorKey(message: string): keyof typeof profileMessages.en | null {
  if (/between 2 and 20/i.test(message)) return 'errNameLength';
  if (/can only contain/i.test(message)) return 'errNameChars';
  if (/reserved/i.test(message)) return 'errNameReserved';
  return null;
}
